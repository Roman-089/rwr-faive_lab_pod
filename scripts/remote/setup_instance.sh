#!/bin/bash
# One-time (and after every instance restart) setup of a MicroAGI RTX 6000 Pro instance for rwr_faive_lab.
#
# Instance: GPU rtx6000 x1, Advanced -> Image:
#   europe-west4-docker.pkg.dev/micro-research-shared/nvcr-mirror/nvidia/isaac-lab:2.3.2
# (Isaac Lab 2.3.2 + Isaac Sim 5.1 preinstalled at /workspace/isaaclab, same versions as on DTU). The image is not
# the stock one, so container changes are not snapshotted: this script re-installs our few Python extras each start
# (~1 min). The repo lives in the persistent home directory.
#
# Usage (after `ssh` to the instance):
#   sudo -i                                   # root login shell: puts the injected NVIDIA driver on PATH
#   git clone -b ablation-study git@github.com:rwr-fast/rwr_faive_lab.git ~/rwr_faive_lab   # first time only
#   bash ~/rwr_faive_lab/scripts/remote/setup_instance.sh
#   wandb login                               # first time only
set -e
REPO=$(cd "$(dirname "$0")/../.." && pwd)
ISAACLAB=${ISAACLAB:-/workspace/isaaclab}
PY="$ISAACLAB/isaaclab.sh -p"
export OMNI_KIT_ALLOW_ROOT=1 OMNI_KIT_ACCEPT_EULA=YES PIP_NO_CACHE_DIR=1

nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv || {
  echo "no GPU visible: run this from a root login shell (sudo -i)"; exit 1; }
cd "$REPO"
command -v git-lfs >/dev/null || { apt-get update -qq && apt-get install -y -qq git-lfs tmux; }
git lfs install -q && git lfs pull

# same versions as the DTU env `rwr` (rsl_rl 3.1.2 is newer than the image's default; eval needs mujoco + imageio)
$PY -m pip install -q rsl-rl-lib==3.1.2 mujoco==3.17.0 imageio==2.37.0 imageio-ffmpeg==0.6.0 wandb tensorboard
$PY -m pip install -q -e source/faive_lab
# (faive_lab itself imports USD and only loads inside a running Isaac Sim app, so check its deps here)
$PY -c "import torch, rsl_rl, mujoco, wandb; print('torch', torch.__version__, 'cuda', torch.cuda.is_available(), torch.cuda.get_device_name(0))"

cat > "$HOME/rwr_env.sh" <<EOF
# generated by scripts/remote/setup_instance.sh; source it in interactive shells
export OMNI_KIT_ALLOW_ROOT=1 OMNI_KIT_ACCEPT_EULA=YES PYTHONUNBUFFERED=1
export WANDB_ENTITY=rwr-fast WANDB_USERNAME=rwr-fast WANDB_DIR=$REPO/logs
export ISAACLAB=$ISAACLAB
alias python="$ISAACLAB/isaaclab.sh -p"
EOF
echo "SETUP_DONE. Next: wandb login (once), then: tmux new -s queue 'bash $REPO/scripts/remote/run_queue.sh 2'"
